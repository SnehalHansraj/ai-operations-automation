"""
OpsPilot Notification Service

Handles notifications generated by the AI Operations Agent.

Notification behaviour:

    AUTO-RESOLVE
        -> log only

    ESCALATE
        -> assign responsible operations team
        -> try email
        -> optionally try Slack
        -> fall back to log if external notification fails

Email uses SMTP and is configured through .env.
"""

import logging
import os
import smtplib
from email.message import EmailMessage

import httpx
from dotenv import load_dotenv

load_dotenv()

logger = logging.getLogger("notifications")


# ============================================================
# CONFIGURATION
# ============================================================

SLACK_WEBHOOK_URL = os.getenv("SLACK_WEBHOOK_URL", "").strip()

SMTP_HOST = os.getenv("SMTP_HOST", "").strip()

SMTP_PORT = int(
    os.getenv("SMTP_PORT", "587")
)

SMTP_USERNAME = os.getenv(
    "SMTP_USERNAME", ""
).strip()

SMTP_PASSWORD = os.getenv(
    "SMTP_PASSWORD", ""
).strip()

SMTP_FROM = os.getenv(
    "SMTP_FROM",
    SMTP_USERNAME,
).strip()

OPS_EMAIL = os.getenv(
    "OPS_EMAIL",
    os.getenv("NOTIFY_EMAIL", ""),
).strip()


# ============================================================
# TEAM ROUTING
# ============================================================

TEAM_ROUTING = {
    "delayed_delivery": {
        "team": "Logistics Operations",
    },

    "customs_hold": {
        "team": "Customs Operations",
    },

    "refund_request": {
        "team": "Billing Operations",
    },

    "damaged_item": {
        "team": "Returns Operations",
    },

    "wrong_item": {
        "team": "Fulfillment Operations",
    },

    "cancellation": {
        "team": "Order Operations",
    },

    "general_inquiry": {
        "team": "Customer Operations",
    },
}


# ============================================================
# TEAM ASSIGNMENT
# ============================================================

def get_assignment(issue_type: str) -> dict:
    """
    Determine which operations team should receive
    an escalated case.
    """

    assignment = TEAM_ROUTING.get(
        issue_type,
        TEAM_ROUTING["general_inquiry"],
    )

    return {
        "team": assignment["team"],
        "email": OPS_EMAIL,
    }


# ============================================================
# EMAIL
# ============================================================

def send_email(
    case_id: str,
    issue_type: str,
    action: str,
    response_text: str,
    team: str,
    recipient: str,
    customer_request: str = "",
    order_status: dict | None = None,
    confidence: float | None = None,
    decision_reason: str = "",
) -> bool:
    """
    Send a detailed operational escalation email.

    Returns:
        True  -> email sent successfully
        False -> email was not sent
    """

    if not recipient:
        logger.warning(
            "Email not sent for case %s: "
            "OPS_EMAIL is not configured.",
            case_id,
        )
        return False

    if not SMTP_HOST:
        logger.warning(
            "Email not sent for case %s: "
            "SMTP_HOST is not configured.",
            case_id,
        )
        return False

    if not SMTP_USERNAME or not SMTP_PASSWORD:
        logger.warning(
            "Email not sent for case %s: "
            "SMTP credentials are not configured.",
            case_id,
        )
        return False

    order_status = order_status or {}

    status = order_status.get(
        "status",
        "unknown",
    )

    location = order_status.get(
        "last_location",
        "unknown",
    )

    eta = order_status.get(
        "eta",
        "unknown",
    )

    days_late = order_status.get(
        "days_since_expected",
        0,
    )

    if confidence is not None:
        confidence_text = (
            f"{confidence * 100:.0f}%"
        )
    else:
        confidence_text = "N/A"

    readable_issue = (
        issue_type
        .replace("_", " ")
        .title()
    )

    subject = (
        f"[OpsPilot] Human Review Required "
        f"— Order #{case_id}"
    )

    body = f"""
Hello {team},

OpsPilot has automatically escalated an operational
case that requires human review.

==================================================
CASE DETAILS
==================================================

Order:
#{case_id}

Issue:
{readable_issue}

AI Confidence:
{confidence_text}

Assigned Team:
{team}


==================================================
CUSTOMER REQUEST
==================================================

{customer_request or "Not available"}


==================================================
SHIPMENT / ORDER DATA
==================================================

Status:
{status}

Last Location:
{location}

Expected Delivery:
{eta}

Days Since Expected:
{days_late}


==================================================
AGENT DECISION
==================================================

Action:
{action}

Reason:
{decision_reason or "Human review required."}


==================================================
CUSTOMER RESPONSE
==================================================

{response_text}


==================================================
REQUIRED ACTION
==================================================

Please review this case and take the appropriate
operational action.

This notification was automatically generated by
OpsPilot — AI Operations Automation.

"""

    try:
        message = EmailMessage()

        message["Subject"] = subject
        message["From"] = SMTP_FROM
        message["To"] = recipient

        message.set_content(
            body.strip()
        )

        logger.info(
            "Connecting to SMTP server %s:%s",
            SMTP_HOST,
            SMTP_PORT,
        )

        with smtplib.SMTP(
            SMTP_HOST,
            SMTP_PORT,
            timeout=10,
        ) as server:

            server.starttls()

            server.login(
                SMTP_USERNAME,
                SMTP_PASSWORD,
            )

            server.send_message(
                message
            )

        logger.info(
            "EMAIL SENT | case=%s | team=%s | recipient=%s",
            case_id,
            team,
            recipient,
        )

        return True

    except Exception as exc:

        logger.exception(
            "EMAIL FAILED | case=%s | error=%s",
            case_id,
            exc,
        )

        return False


# ============================================================
# SLACK
# ============================================================

def send_slack(
    case_id: str,
    issue_type: str,
    action: str,
    response_text: str,
    team: str,
) -> bool:
    """
    Send Slack notification if a webhook is configured.
    """

    if not SLACK_WEBHOOK_URL:
        return False

    message = (
        f":rotating_light: *OpsPilot Human Review*\n\n"
        f"*Case:* #{case_id}\n"
        f"*Issue:* `{issue_type}`\n"
        f"*Action:* `{action}`\n"
        f"*Assigned Team:* `{team}`\n\n"
        f"*Customer Response:*\n"
        f"{response_text}"
    )

    try:

        response = httpx.post(
            SLACK_WEBHOOK_URL,
            json={
                "text": message
            },
            timeout=5,
        )

        response.raise_for_status()

        logger.info(
            "SLACK SENT | case=%s | team=%s",
            case_id,
            team,
        )

        return True

    except Exception as exc:

        logger.warning(
            "SLACK FAILED | case=%s | error=%s",
            case_id,
            exc,
        )

        return False


# ============================================================
# MAIN NOTIFICATION TOOL
# ============================================================

def notify(
    case_id: str,
    issue_type: str,
    action: str,
    response_text: str,
    customer_request: str = "",
    order_status: dict | None = None,
    confidence: float | None = None,
    decision_reason: str = "",
) -> str:
    """
    Main notification tool used by the agent.

    Returns:

        "email"
            Email notification successfully sent.

        "slack"
            Slack notification successfully sent.

        "log"
            No external notification was sent.
    """

    assignment = get_assignment(
        issue_type
    )

    team = assignment["team"]
    recipient = assignment["email"]

    logger.info(
        "NOTIFICATION | case=%s | issue=%s | action=%s | team=%s",
        case_id,
        issue_type,
        action,
        team,
    )

    # --------------------------------------------------------
    # AUTO-RESOLVED CASE
    # --------------------------------------------------------

    if action != "escalate":

        logger.info(
            "AUTO-RESOLVED | case=%s | no human notification required",
            case_id,
        )

        return "log"

    # --------------------------------------------------------
    # ESCALATED CASE
    # --------------------------------------------------------

    logger.info(
        "ESCALATION | case=%s | assigned_team=%s | recipient=%s",
        case_id,
        team,
        recipient or "not configured",
    )

    # --------------------------------------------------------
    # 1. EMAIL
    # --------------------------------------------------------

    email_sent = send_email(
        case_id=case_id,
        issue_type=issue_type,
        action=action,
        response_text=response_text,
        team=team,
        recipient=recipient,
        customer_request=customer_request,
        order_status=order_status,
        confidence=confidence,
        decision_reason=decision_reason,
    )

    if email_sent:
        return "email"

    # --------------------------------------------------------
    # 2. SLACK
    # --------------------------------------------------------

    slack_sent = send_slack(
        case_id=case_id,
        issue_type=issue_type,
        action=action,
        response_text=response_text,
        team=team,
    )

    if slack_sent:
        return "slack"

    # --------------------------------------------------------
    # 3. LOG FALLBACK
    # --------------------------------------------------------

    logger.warning(
        "NOTIFICATION FALLBACK | "
        "case=%s | team=%s | action=%s",
        case_id,
        team,
        action,
    )

    return "log"